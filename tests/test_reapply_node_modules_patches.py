"""_ensure_api_modules_installed() reapplying node_modules-level patches
(host.layer.js, status.layer.js, sender.layer.js) on every startup, not just
as a side effect of running npm install for a missing package.

Reported live: a WinZapp update shipped a new node_modules patch
(sender.layer.js's sendFile error-detail fix) with no new npm dependency.
On a machine that already had node_modules fully installed from an earlier
version, `missing` (the required-package-marker check) came back empty, so
the npm-install branch — the ONLY place that reapplied
ApiSetupDialog._apply_node_modules_patches() — never ran. The new patch
silently never took effect until a full API reinstall, even after
rebuilding and relaunching WinZapp with the fix already in the source.

Fix: when nothing is missing, still call _apply_node_modules_patches()
(each of its underlying _patch_* methods is an idempotent, cheap string
search — a no-op if the patch is already applied).
"""

import os

import pytest

from main import MainWindow


class _Stub:
    """MainWindow is a wx.Frame and cannot be instantiated without a wx.App,
    so the method under test is bound onto a plain object carrying only what
    it touches — same approach as tests/test_headless_shell_install.py."""

    _ensure_api_modules_installed = MainWindow._ensure_api_modules_installed
    background_mode = False

    def _find_api_ffmpeg(self):
        return "/fake/ffmpeg.exe"


@pytest.fixture
def fully_installed_api(tmp_path, monkeypatch):
    """A machine with a complete, already-installed API — start.js,
    node.exe, dist/server.js, and node_modules with the @wppconnect-team
    marker and the @babel/runtime required-package marker both present, so
    the "missing packages" branch has nothing to report."""
    import main

    api = tmp_path / "api"
    (api / "dist").mkdir(parents=True)
    (api / "dist" / "server.js").write_text("// built", encoding="utf-8")
    (api / "start.js").write_text("// start", encoding="utf-8")
    node_modules = api / "node_modules"
    (node_modules / "@wppconnect-team" / "wppconnect").mkdir(parents=True)
    (node_modules / "@babel" / "runtime").mkdir(parents=True)

    node_dir = tmp_path / "node"
    node_dir.mkdir()
    (node_dir / "node.exe").write_text("binary", encoding="utf-8")
    npm_cli = node_dir / "node_modules" / "npm" / "bin" / "npm-cli.js"
    npm_cli.parent.mkdir(parents=True)
    npm_cli.write_text("// npm", encoding="utf-8")

    def fake_resource_path(*parts):
        return str(tmp_path.joinpath(*parts))

    monkeypatch.setattr(main, "resource_path", fake_resource_path)
    monkeypatch.setattr(main.sys, "platform", "win32")

    class _ProbeResult:
        returncode = 0
        stdout = "v22.22.2\n"
        stderr = ""

    # Runtime-health probes happen before the package-marker branch under
    # test. Keep those successful so Popen below continues to mean only the
    # npm installation whose presence/absence each test is asserting.
    monkeypatch.setattr(main.subprocess, "run", lambda *a, **k: _ProbeResult())
    return api


def test_patches_are_reapplied_even_when_no_package_is_missing(fully_installed_api, monkeypatch):
    import main
    from ui.dialogs.api_setup import ApiSetupDialog

    calls = []
    monkeypatch.setattr(
        ApiSetupDialog, "_apply_node_modules_patches",
        staticmethod(lambda api_dir: calls.append(api_dir)),
    )
    monkeypatch.setattr(
        main.subprocess, "Popen",
        lambda *a, **k: (_ for _ in ()).throw(AssertionError("must not run npm install — nothing is missing")),
    )

    _Stub()._ensure_api_modules_installed()

    assert calls == [str(fully_installed_api)]


def test_a_missing_package_still_reapplies_patches_via_the_install_branch(fully_installed_api, monkeypatch):
    """Sanity check the pre-existing behavior is untouched: when a package
    really is missing, npm install still runs and patches still get
    reapplied afterwards (through the other branch, not the new one)."""
    import main
    from ui.dialogs.api_setup import ApiSetupDialog

    os.rmdir(str(fully_installed_api / "node_modules" / "@babel" / "runtime"))

    calls = []
    monkeypatch.setattr(
        ApiSetupDialog, "_apply_node_modules_patches",
        staticmethod(lambda api_dir: calls.append(api_dir)),
    )

    class FakeProc:
        returncode = 0

        def communicate(self, timeout=None):
            return (b"", b"")

    monkeypatch.setattr(main.subprocess, "Popen", lambda *a, **k: FakeProc())

    _Stub()._ensure_api_modules_installed()

    assert calls == [str(fully_installed_api)]


def test_a_failure_to_reapply_patches_is_logged_not_fatal(fully_installed_api, monkeypatch):
    import main
    from ui.dialogs.api_setup import ApiSetupDialog

    def boom(api_dir):
        raise OSError("disk full")

    monkeypatch.setattr(ApiSetupDialog, "_apply_node_modules_patches", staticmethod(boom))
    monkeypatch.setattr(
        main.subprocess, "Popen",
        lambda *a, **k: (_ for _ in ()).throw(AssertionError("must not run npm install")),
    )

    _Stub()._ensure_api_modules_installed()  # must not raise
